/*
 * The DSP mixer's driver (platform/wii/dsp_mix.h, tools/dsp/dspmix.s). The microcode is loaded with libogc's
 * DSP_AddTask as the AESND library does (the ROM's boot protocol); its init mail comes in through the task's
 * init callback, the callback tells it where the command blocks are, and from there on a run is one mail to the DSP
 * and one mail back (polled: the microcode raises no interrupt for it). AESND is part of libogc; see CREDITS.md.
 */
#include "dsp_mix.h"

#include <gccore.h>
#include <ogc/machine/processor.h>
#include <ogc/lwp_watchdog.h>
#include <stdio.h>
#include <string.h>

#include "dspmix.h"             /* generated by gcdsptool from tools/dsp/dspmix.s: dspmix[], dspmix_size */

extern void plat_log(const char *fmt, ...);

/* The console has the chip idle; the CPU's mixer is one of the larger items of a race frame (2026-10-23), so it
 * runs the DSP by default. Under Dolphin it is turned off (plat_init: HLE does not know this microcode, and LLE is
 * slower than the CPU it would relieve); args.txt "--dsp 0" or the autopilot's "dsp 0" turns it off anywhere. */
int g_dsp_on = 1;

enum { ST_OFF, ST_STARTING, ST_UP, ST_FAILED };

/* a slot's command block, 1 KB apart (the microcode finds block k at the base + k * 1024) */
typedef union CmdSlot {
    DspMixCmd c;
    uint8_t b[1024];
} CmdSlot;
typedef char cmd_fits[sizeof(DspMixCmd) <= 1024 ? 1 : -1];

static dsptask_t g_task;
static volatile int g_state;
static volatile int g_init_seen;
static CmdSlot *g_cmd;                  /* DSPMIX_SLOTS of them, and the sums: MEM1, taken when the DSP is started */
static DspMixSum (*g_sum)[2][DSPMIX_CHUNK];
static uint32_t g_runs, g_answers, g_failed_how, g_wait_max_us, g_late, g_box_waits;
static uint64_t g_kick_us[DSPMIX_SLOTS];
static uint32_t g_samples[DSPMIX_SLOTS];
static uint32_t g_cores[DSPMIX_SLOTS];  /* a run's cores that had a job (bit 0, bit 1): the DSP sends no others */
static int g_fifo[DSPMIX_SLOTS], g_fifo_n;  /* the slots out, oldest first */
static int g_fifo_sent;                 /* how many of them have been mailed (the box holds one: the rest wait here) */

static inline uint64_t now_us(void)
{
    return ticks_to_microsecs(gettime());
}

void *dspmix_mem(uint32_t bytes)
{
    uint32_t level;
    uint8_t *lo;
    _CPU_ISR_Disable(level);
    lo = (uint8_t *)(((uintptr_t)SYS_GetArena1Lo() + 31) & ~(uintptr_t)31);
    bytes = (bytes + 31) & ~31u;
    if (lo + bytes > (uint8_t *)SYS_GetArena1Hi()) {
        lo = NULL;
    } else {
        SYS_SetArena1Lo(lo + bytes);
        memset(lo, 0, bytes);
    }
    _CPU_ISR_Restore(level);
    return lo;
}

/* a mail to the DSP, with a bound on the wait for its box to empty (the libogc calls wait for ever) */
static int mail_send(uint32_t mail)
{
    uint32_t spin;
    DSP_SendMailTo(mail);
    for (spin = 0; DSP_CheckMailTo(); spin++)
        if (spin > 200000)
            return 0;
    return 1;
}

static void init_cb(dsptask_t *task)
{
    (void)task;
    if (mail_send(0xFACE0080) && mail_send((uint32_t)&g_cmd[0] & 0x1FFFFFFFu))
        g_init_seen = 1;
}

int dspmix_up(void)
{
    return g_state == ST_UP;
}

int dspmix_start(void)
{
    uint64_t t0;
    if (g_state == ST_UP)
        return 1;
    if (g_state != ST_OFF)
        return 0;
    g_state = ST_STARTING;
    g_cmd = dspmix_mem(DSPMIX_SLOTS * sizeof(CmdSlot));
    g_sum = dspmix_mem(DSPMIX_SLOTS * sizeof g_sum[0]);
    if (!g_cmd || !g_sum) {
        g_state = ST_FAILED;
        plat_log("dsp: no room in MEM1 for the mixer's command blocks");
        return 0;
    }
    DCFlushRange(g_cmd, DSPMIX_SLOTS * sizeof(CmdSlot));
    DSP_Init();
    DCFlushRange((void *)dspmix, dspmix_size);
    memset(&g_task, 0, sizeof g_task);
    g_task.prio = 255;
    g_task.iram_maddr = (void *)((uint32_t)dspmix & 0x1FFFFFFFu);
    g_task.iram_len = dspmix_size;
    g_task.iram_addr = 0x0000;
    g_task.dram_maddr = NULL;
    g_task.dram_len = 0;
    g_task.dram_addr = 0x0000;
    g_task.init_vec = 0x0010;
    g_task.init_cb = init_cb;
    t0 = now_us();
    DSP_AddTask(&g_task);
    while (!g_init_seen && now_us() - t0 < 300000)
        ;
    if (!g_init_seen) {
        g_state = ST_FAILED;
        plat_log("dsp: the mixer microcode did not come up in 300 ms");
        return 0;
    }
    g_state = ST_UP;
    plat_log("dsp: mixer microcode up after %u us (%u bytes, command blocks %08X)", (unsigned)(now_us() - t0), (unsigned)dspmix_size,
             (unsigned)((uint32_t)&g_cmd[0] & 0x1FFFFFFFu));
    return 1;
}

DspMixCmd *dspmix_cmd(int slot)
{
    return &g_cmd[slot].c;
}

static void give_up(uint32_t how)
{
    g_state = ST_FAILED;
    g_failed_how = how;
    g_fifo_n = g_fifo_sent = 0;
}

/* runs that wait for the mail box go into it as it empties (the DSP takes the next mail when it has done a run) */
static void send_waiting(void)
{
    while (g_fifo_sent < g_fifo_n && !DSP_CheckMailTo()) {
        const int slot = g_fifo[g_fifo_sent++];
        g_kick_us[slot] = now_us();
        DSP_SendMailTo(0xFACE0010u + (uint32_t)slot);
    }
}

int dspmix_run(int slot, uint32_t jobs, uint32_t samples, const DspMixRecord *records)
{
    DspMixCmd *c = &g_cmd[slot].c;
    const uint32_t res = (uint32_t)g_sum[slot] & 0x1FFFFFFFu, rec = (uint32_t)records & 0x1FFFFFFFu;
    uint32_t j;
    if (g_state != ST_UP || g_fifo_n >= DSPMIX_SLOTS)
        return 0;
    g_cores[slot] = 0;
    for (j = 0; j < jobs; j++)
        g_cores[slot] |= 1u << (c->job[j].coref & 1);
    c->jobs = (uint16_t)jobs;
    c->samples = (uint16_t)samples;
    c->res_hi = (uint16_t)(res >> 16);
    c->res_lo = (uint16_t)res;
    c->rec_hi = (uint16_t)(rec >> 16);
    c->rec_lo = (uint16_t)rec;
    g_samples[slot] = samples;
    DCFlushRange(c, 32 + jobs * sizeof(DspMixJob));
    /* the box holds one mail: with a run going on and one in the box, this one waits here for its turn */
    g_fifo[g_fifo_n++] = slot;
    g_runs++;
    if (g_fifo_sent < g_fifo_n - 1 || DSP_CheckMailTo())
        g_box_waits++;
    send_waiting();
    return 1;
}

int dspmix_out(void)
{
    return g_state == ST_UP ? g_fifo_n : 0;
}

int dspmix_poll(void)
{
    uint32_t mail, m4;
    int slot, k;
    if (g_state != ST_UP || !g_fifo_n)
        return -1;
    send_waiting();
    if (!g_fifo_sent || !DSP_CheckMailFrom())
        return -1;
    mail = DSP_ReadMailFrom();
    if ((mail >> 16) != 0xBEEFu || (mail & 0xFFFFu) != ((g_answers + 1) & 0xFFFFu)) {
        give_up(2);
        plat_log("dsp: unexpected mail %08X from the mixer microcode (run %u): given up", (unsigned)mail, (unsigned)(g_answers + 1));
        return -1;
    }
    g_answers++;
    slot = g_fifo[0];
    for (k = 1; k < g_fifo_n; k++)
        g_fifo[k - 1] = g_fifo[k];
    g_fifo_n--;
    g_fifo_sent--;
    send_waiting();
    {
        const uint32_t us = (uint32_t)(now_us() - g_kick_us[slot]);
        if (us > g_wait_max_us)
            g_wait_max_us = us;
    }
    m4 = (g_samples[slot] + 3) & ~3u;
    if (g_cores[slot] & 1)
        DCInvalidateRange(g_sum[slot][0], m4 * sizeof(DspMixSum));
    if (g_cores[slot] & 2)
        DCInvalidateRange(g_sum[slot][1], m4 * sizeof(DspMixSum));
    return slot;
}

int dspmix_wait(uint32_t timeout_us)
{
    const uint64_t t0 = now_us();
    if (g_state != ST_UP || !g_fifo_n)
        return -1;
    for (;;) {
        const int slot = dspmix_poll();
        if (slot >= 0)
            return slot;
        if (g_state != ST_UP)
            return -1;
        if (now_us() - t0 > timeout_us) {
            plat_log("dsp: the mixer microcode did not answer in %u us (run %u, %u answered, %d of %d out mailed): given up",
                     (unsigned)timeout_us, (unsigned)(g_answers + 1), (unsigned)g_answers, g_fifo_sent, g_fifo_n);
            give_up(3);
            return -1;
        }
        g_late++;
    }
}

const DspMixSum *dspmix_sums(int slot, int core)
{
    return g_cores[slot] >> (core & 1) & 1 ? g_sum[slot][core & 1] : NULL;
}

void dspmix_report(char *line, unsigned size)
{
    snprintf(line, size, "dsp mixer %s: %u runs, %u answered, slowest answer %u us after the kick, %u polls that found it not ready, "
             "%u runs that waited for the mail box%s",
             g_state == ST_UP ? "up" : g_state == ST_FAILED ? "FAILED" : "off", (unsigned)g_runs, (unsigned)g_answers, (unsigned)g_wait_max_us,
             (unsigned)g_late, (unsigned)g_box_waits, g_failed_how ? " (failed)" : "");
    g_wait_max_us = 0;
    g_late = 0;
    g_box_waits = 0;
}
